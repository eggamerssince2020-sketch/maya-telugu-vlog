        foreign_scripts_detected = bool(re.search(r"[\u4E00-\u9FFF\u3040-\u30FF\u0D00-\u0D7F\u0530-\u058F\u0980-\u09FF\u0600-\u06FF\u0400-\u04FF\u0E00-\u0E7F]", raw_json))
