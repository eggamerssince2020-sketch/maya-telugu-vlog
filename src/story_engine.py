"""
Story Engine module for maya-telugu-vlog.
Implements a 2-stage LLM pipeline via OpenRouter:
  Stage 1 (Story Architect): High-chemistry scene plotting and visual prompt structuring.
  Stage 2 (Telugu Writer): Spoken, colloquial Telugu vlog prose formatting and Telegram poll crafting.
Validates the final output with a strict Pydantic v2 model.
"""

import json
import logging
import re
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator
import openai

from src.config import Settings

logger = logging.getLogger(__name__)


def clean_telugu_text(text: str) -> str:
    """
    Sanitizes Telugu text:
    - Retains only Telugu script (\u0C00-\u0C7F), English alphanumeric, standard punctuation,
      common emojis, and Telegram-safe HTML tags (<b>, </i>, etc.).
    - Strips foreign scripts (Thai, Bengali, Devanagari, Chinese, Cyrillic, Arabic).
    - Fixes awkward mechanical machine-translation artifacts into natural spoken Telugu.
    """
    # 1. Strip non-Telugu / non-Latin foreign scripts and bizarre symbols
    # Allowed: Telugu (\u0C00-\u0C7F), ASCII printable, common punctuation & emojis
    foreign_pattern = r"[\u4E00-\u9FFF\u0600-\u06FF\uAC00-\uD7AF\u0400-\u04FF\u0900-\u097F\u0590-\u05FF\u0E00-\u0E7F\u0980-\u09FF\u0B80-\u0BFF]"
    cleaned = re.sub(foreign_pattern, "", text)

    # 2. Fix awkward literal translation artifacts if generated by non-Indic LLMs
    translations_fixes = [
        (r"వెల్లుల్లి\s*వాసన", "తడిసిన మట్టి సువాసన"),
        (r"వెల్లుల్లి", "పరిమళం"),
        (r"ఆవు\s*గాలి", "వెచ్చని శ్వాస"),
        (r"ఆవు\s*ఊపిరి", "వేడి శ్వాస"),
        (r"శల్యము", "శరీరం"),
    ]
    for pattern, repl in translations_fixes:
        cleaned = re.sub(pattern, repl, cleaned)

    # 3. Clean excessive whitespace
    cleaned = re.sub(r"[ \t]+", " ", cleaned)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip()


class EpisodePayload(BaseModel):
    """Strict Pydantic v2 model representing an episode ready for generation and publishing."""

    episode_title_te: str = Field(
        description="Catchy Telugu vlog title with episode number and emojis"
    )
    teaser_caption_te: str = Field(
        description="High-heat opening hook in Telugu (strictly under 850 chars) ending with call-to-action"
    )
    full_story_te: str = Field(
        description="Sensual, intimate first-person Telugu vlog story (1800-3200 chars) with Telegram HTML tags"
    )
    image_prompt_en: str = Field(
        description="Detailed photorealistic Flux LoRA prompt describing Maya in the exact scene outfit and pose"
    )
    outfit_used: str = Field(
        description="Short description of today's distinct outfit"
    )
    summary_en: str = Field(
        description="3-sentence English narrative summary for continuity memory"
    )
    poll_question_te: str = Field(
        description="Spicy Telugu decision question for tomorrow night (max 250 chars)"
    )
    poll_options_te: List[str] = Field(
        description="2 to 3 tempting, contrasting Telugu poll choices (max 95 chars each)"
    )

    @field_validator("teaser_caption_te")
    @classmethod
    def validate_teaser_length(cls, v: str) -> str:
        trimmed = clean_telugu_text(v)
        cta = "\n\n👇 పూర్తి స్టోరీ కింద మెసేజ్లో చదవండి..."
        if len(trimmed) > 850:
            # Safely trim to ensure Telegram caption limit and prompt requirement
            allowed_len = 840 - len(cta)
            trimmed = trimmed[:allowed_len].rsplit(" ", 1)[0] + "..." + cta
        elif "పూర్తి స్టోరీ కింద మెసేజ్లో చదవండి" not in trimmed:
            trimmed = trimmed + cta
        return trimmed

    @field_validator("full_story_te")
    @classmethod
    def validate_story_length(cls, v: str) -> str:
        trimmed = clean_telugu_text(v)
        if len(trimmed) < 1000:
            logger.warning("Story text shorter than expected (%d chars).", len(trimmed))
        return trimmed

    @field_validator("poll_question_te")
    @classmethod
    def validate_poll_question(cls, v: str) -> str:
        trimmed = clean_telugu_text(v)
        if len(trimmed) > 250:
            trimmed = trimmed[:247] + "..."
        return trimmed

    @field_validator("poll_options_te")
    @classmethod
    def validate_poll_options(cls, v: List[str]) -> List[str]:
        cleaned = [clean_telugu_text(opt)[:95] for opt in v if opt.strip()]
        if len(cleaned) < 2:
            cleaned.append("మాయ ధైర్యంగా ముందుకు అడుగు వేయాలి")
        return cleaned[:3]


class StoryEngine:
    """Orchestrates Stage 1 (Architect) and Stage 2 (Telugu Writer) LLM calls."""

    def __init__(self, settings: Settings):
        self.settings = settings
        self.client: Optional[openai.OpenAI] = None
        self.provider = "none"

        has_gemini = bool(self.settings.GEMINI_API_KEY and not self.settings.GEMINI_API_KEY.startswith("your_"))
        has_openrouter = bool(self.settings.OPENROUTER_API_KEY and not self.settings.OPENROUTER_API_KEY.startswith("your_"))
        self._is_live = bool((has_gemini or has_openrouter) and not self.settings.MOCK_MODE)

        if self._is_live:
            if has_gemini:
                logger.info("Initializing StoryEngine with Google Gemini direct API (Model: %s)...", self.settings.GEMINI_MODEL)
                self.client = openai.OpenAI(
                    base_url="https://generativelanguage.googleapis.com/v1beta/openai/",
                    api_key=self.settings.GEMINI_API_KEY,
                )
                self.provider = "gemini"
            elif has_openrouter:
                logger.info("Initializing StoryEngine with OpenRouter API (Base: %s)...", self.settings.OPENROUTER_BASE_URL)
                self.client = openai.OpenAI(
                    base_url=self.settings.OPENROUTER_BASE_URL,
                    api_key=self.settings.OPENROUTER_API_KEY,
                )
                self.provider = "openrouter"

    def _call_llm(self, model: str, system_prompt: str, user_prompt: str, temperature: float = 0.85) -> str:
        """Helper to invoke LLM with automatic retry, backoff, and fallback."""
        if not self.client:
            raise RuntimeError("LLM client not initialized.")

        # If using Gemini directly, route to Gemini model
        if self.provider == "gemini":
            target_model = self.settings.GEMINI_MODEL
            logger.info("Calling Google Gemini model '%s'...", target_model)
            response = self.client.chat.completions.create(
                model=target_model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=temperature,
                timeout=60.0,
            )
            return response.choices[0].message.content or ""

        # OpenRouter fallback list
        models_to_try = [model]
        if ":free" in model or model == "openrouter/free":
            backup_models = [
                "google/gemma-4-31b-it:free",
                "google/gemma-4-26b-a4b-it:free",
                "openrouter/free",
                "nvidia/nemotron-3-ultra-550b-a55b:free",
                "nvidia/nemotron-3.5-lightning:free",
            ]
            for b in backup_models:
                if b not in models_to_try:
                    models_to_try.append(b)

        last_err = None
        for m in models_to_try:
            for attempt in range(2):
                try:
                    logger.info("Calling OpenRouter model '%s' (attempt %d)...", m, attempt + 1)
                    response = self.client.chat.completions.create(
                        model=m,
                        messages=[
                            {"role": "system", "content": system_prompt},
                            {"role": "user", "content": user_prompt},
                        ],
                        temperature=temperature,
                        timeout=60.0,
                    )
                    msg = response.choices[0].message
                    content = msg.content or getattr(msg, "reasoning", "") or ""
                    if content and len(content.strip()) > 20:
                        return content
                except Exception as e:
                    logger.warning("LLM call to model '%s' (attempt %d) failed: %s.", m, attempt + 1, e)
                    last_err = e
                    import time
                    time.sleep(1.5)

        raise RuntimeError(f"All LLM models failed: {last_err}")

    def generate_episode(
        self,
        episode_number: int,
        arc: Dict[str, Any],
        winning_poll_choice: Optional[str],
        past_summaries: List[str],
        recent_outfits: List[str],
    ) -> EpisodePayload:
        """
        Executes the 2-stage generation pipeline or returns an authentic mock payload.
        """
        if not self._is_live:
            logger.info("Using mock StoryEngine generation (MOCK_MODE or missing API key).")
            return self._generate_mock_episode(episode_number, winning_poll_choice)

        try:
            logger.info("Executing Stage 1: Story Architect with model '%s'...", self.settings.STORY_ARCHITECT_MODEL)
            architect_output = self._run_stage1_architect(
                episode_number=episode_number,
                arc=arc,
                winning_poll_choice=winning_poll_choice,
                past_summaries=past_summaries,
                recent_outfits=recent_outfits,
            )

            logger.info("Executing Stage 2: Telugu Writer with model '%s'...", self.settings.TELUGU_WRITER_MODEL)
            payload = self._run_stage2_telugu_writer(
                episode_number=episode_number,
                architect_output=architect_output,
                winning_poll_choice=winning_poll_choice,
            )
            return payload
        except Exception as e:
            logger.error("Error during 2-stage episode generation: %s. Using fail-safe authentic Telugu episode.", e)
            return self._generate_mock_episode(episode_number, winning_poll_choice)

